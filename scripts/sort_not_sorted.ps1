function Get-Norm([string]$s) {
    # Lowercase, strip accents (ë -> e, ³ -> 3, fullwidth -> ascii), punctuation -> spaces.
    if (-not $s) { return '' }
    $d = $s.Normalize([Text.NormalizationForm]::FormKD)
    $sb = New-Object Text.StringBuilder
    foreach ($c in $d.ToCharArray()) {
        if ([Globalization.CharUnicodeInfo]::GetUnicodeCategory($c) -eq
            [Globalization.UnicodeCategory]::NonSpacingMark) { continue }
        if ([char]::IsLetterOrDigit($c)) { [void]$sb.Append([char]::ToLowerInvariant($c)) }
        else { [void]$sb.Append(' ') }
    }
    return (($sb.ToString() -replace '\s+', ' ').Trim())
}

function Get-NormAccent([string]$s) {
    # Like Get-Norm but keeps accents, so "Back homë" and "Back Home" differ.
    if (-not $s) { return '' }
    $s = $s.Normalize([Text.NormalizationForm]::FormC).ToLowerInvariant()
    return (($s -replace '[^\p{L}\p{N}]+', ' ').Trim())
}

function Test-Words([string]$hay, [string]$needle) {
    # True when $needle appears in $hay as whole words.
    if (-not $needle) { return $false }
    return (" $hay ").Contains(" $needle ")
}

function Remove-WordsOnce([string]$hay, [string]$needle) {
    if (-not $needle) { return $hay }
    $padded = " $hay "
    $i = $padded.IndexOf(" $needle ")
    if ($i -lt 0) { return $hay }
    return (($padded.Remove($i, $needle.Length + 1)) -replace '\s+', ' ').Trim()
}

