function Find-Track([string]$baseName) {
    # Returns @(entry, how) or @($null, reason).
    for ($i = 0; $i -le $baseName.Length - 11; $i++) {
        $id = $baseName.Substring($i, 11)
        if ($ById.ContainsKey($id)) { return @($ById[$id], 'video id') }
    }

    $n = Get-Norm $baseName
    $best = $null
    if ($ByTitle.ContainsKey($n)) { $best = $n }
    else {
        foreach ($k in $ByTitle.Keys) {
            if ((Test-Words $n $k) -and (-not $best -or $k.Length -gt $best.Length)) { $best = $k }
        }
    }
    if ($best) {
        $hits = @($ByTitle[$best])
        if (@($hits | ForEach-Object { "$($_.Entry.Album.Key)|$($_.Entry.Track)" } | Select-Object -Unique).Count -gt 1) {
            $na = Get-NormAccent $baseName
            $hits = @($hits | Where-Object { Test-Words $na $_.Accent })
        }
        $keys = @($hits | ForEach-Object { "$($_.Entry.Album.Key)|$($_.Entry.Track)" } | Select-Object -Unique)
        if ($keys.Count -eq 1) { return @($hits[0].Entry, 'video title') }
        $why = 'ambiguous: ' + ((@($ByTitle[$best]) | ForEach-Object { "$($_.Entry.Album.album) / $($_.Entry.Track)" }) -join ' or ')
        return @($null, $why)
    }

    $cands = @()
    foreach ($e in $Entries) {
        $hit = @($e.TrackNorms | Where-Object { Test-Words $n $_ } | Sort-Object Length -Descending) | Select-Object -First 1
        if (-not $hit) { continue }
        $artistHit = @($e.Album.ArtistNorms | Where-Object { Test-Words $n $_ }).Count -gt 0
        # Look for the album name outside the track name, so a title track
        # ("LYFESTYLE" on LYFESTYLE) doesn't count as naming the album.
        $rest = Remove-WordsOnce $n $hit
        $albumHit = @($e.Album.AlbumNorms | Where-Object { Test-Words $rest $_ }).Count -gt 0
        $cands += [pscustomobject]@{ Entry = $e; ArtistHit = $artistHit; Norm = $hit
            Score = $hit.Length + $(if ($albumHit) { 500 } else { 0 }) }
    }
    if (-not $cands) { return @($null, 'no track name matched') }

    $withArtist = @($cands | Where-Object { $_.ArtistHit })
    if ($withArtist) { $cands = $withArtist }
    else {
        $c = $cands | Sort-Object Score -Descending | Select-Object -First 1
        if ($TrackNameCount[$c.Norm] -eq 1 -and $c.Norm.Length -ge 6) {
            return @($c.Entry, 'track name only')
        }
        return @($null, 'track name found but no artist in file name')
    }

    $top = ($cands | Measure-Object Score -Maximum).Maximum
    $winners = @($cands | Where-Object { $_.Score -eq $top })
    $keys = @($winners | ForEach-Object { $_.Entry.Album.Key } | Select-Object -Unique)
    if ($keys.Count -gt 1) {
        $why = 'ambiguous: ' + (($winners | ForEach-Object { "$($_.Entry.Album.album) / $($_.Entry.Track)" }) -join ' or ')
        return @($null, $why)
    }
    return @($winners[0].Entry, 'artist + track name')
}

